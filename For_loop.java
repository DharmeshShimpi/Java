public class For_loop {
    
    public static void main(String[] args) {

        // for loop executes limited amount of time whereas while loop that could execute an infinite amount of times if the condition is true!
        
        for(int i = 10; i>=0; i--) {
            System.out.println(i);
        }

        System.out.println("Happy New Year!");
    }
}
